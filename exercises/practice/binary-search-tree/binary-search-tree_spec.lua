local BinarySearchTree = require('binary-search-tree')

describe('binary-search-tree', function()
  local function sorted_values(tree)
    local values = {}
    for value in tree:values() do
      table.insert(values, value)
    end
    return values
  end

  it('data is retained', function()
    local tree = BinarySearchTree:from_list({ 4 })
    assert.equal(4, tree.value)
    assert.is_nil(tree.left)
    assert.is_nil(tree.right)
  end)

  describe('insert data at proper node', function()
    it('smaller number at left node', function()
      local tree = BinarySearchTree:from_list({ 4, 2 })
      assert.equal(4, tree.value)
      assert.equal(2, tree.left.value)
      assert.is_nil(tree.left.left)
      assert.is_nil(tree.left.right)
      assert.is_nil(tree.right)
    end)

    it('same number at left node', function()
      local tree = BinarySearchTree:from_list({ 4, 4 })
      assert.equal(4, tree.value)
      assert.equal(4, tree.left.value)
      assert.is_nil(tree.left.left)
      assert.is_nil(tree.left.right)
      assert.is_nil(tree.right)
    end)

    it('greater number at right node', function()
      local tree = BinarySearchTree:from_list({ 4, 5 })
      assert.equal(4, tree.value)
      assert.is_nil(tree.left)
      assert.equal(5, tree.right.value)
      assert.is_nil(tree.right.left)
      assert.is_nil(tree.right.right)
    end)
  end)

  it('can create complex tree', function()
    local tree = BinarySearchTree:from_list({ 4, 2, 6, 1, 3, 5, 7 })
    assert.equal(4, tree.value)
    assert.equal(2, tree.left.value)
    assert.equal(1, tree.left.left.value)
    assert.is_nil(tree.left.left.left)
    assert.is_nil(tree.left.left.right)
    assert.equal(3, tree.left.right.value)
    assert.is_nil(tree.left.right.left)
    assert.is_nil(tree.left.right.right)
    assert.equal(6, tree.right.value)
    assert.equal(5, tree.right.left.value)
    assert.is_nil(tree.right.left.left)
    assert.is_nil(tree.right.left.right)
    assert.equal(7, tree.right.right.value)
    assert.is_nil(tree.right.right.left)
    assert.is_nil(tree.right.right.right)
  end)

  describe('can sort data', function()
    it('can sort single number', function()
      local tree = BinarySearchTree:from_list({ 2 })
      assert.same({ 2 }, sorted_values(tree))
    end)

    it('can sort if second number is smaller than first', function()
      local tree = BinarySearchTree:from_list({ 2, 1 })
      assert.same({ 1, 2 }, sorted_values(tree))
    end)

    it('can sort if second number is same as first', function()
      local tree = BinarySearchTree:from_list({ 2, 2 })
      assert.same({ 2, 2 }, sorted_values(tree))
    end)

    it('can sort if second number is greater than first', function()
      local tree = BinarySearchTree:from_list({ 2, 3 })
      assert.same({ 2, 3 }, sorted_values(tree))
    end)

    it('can sort complex tree', function()
      local tree = BinarySearchTree:from_list({ 2, 1, 3, 6, 7, 5 })
      assert.same({ 1, 2, 3, 5, 6, 7 }, sorted_values(tree))
    end)
  end)
end)
