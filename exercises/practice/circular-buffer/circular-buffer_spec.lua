local CircularBuffer = require('circular-buffer')

describe('circular-buffer', function()
  it('reading empty buffer should fail', function()
    local buffer = CircularBuffer:new(1)
    assert.has_error(function()
      buffer:read()
    end, 'buffer is empty')
  end)

  it('can read an item just written', function()
    local buffer = CircularBuffer:new(1)
    buffer:write(1)
    assert.are.equal(1, buffer:read())
  end)

  it('each item may only be read once', function()
    local buffer = CircularBuffer:new(1)
    buffer:write(1)
    assert.are.equal(1, buffer:read())
    assert.has_error(function()
      buffer:read()
    end, 'buffer is empty')
  end)

  it('items are read in the order they are written', function()
    local buffer = CircularBuffer:new(2)
    buffer:write(1)
    buffer:write(2)
    assert.are.equal(1, buffer:read())
    assert.are.equal(2, buffer:read())
  end)

  it("full buffer can't be written to", function()
    local buffer = CircularBuffer:new(1)
    buffer:write(1)
    assert.has_error(function()
      buffer:write(2)
    end, 'buffer is full')
  end)

  it('a read frees up capacity for another write', function()
    local buffer = CircularBuffer:new(1)
    buffer:write(1)
    assert.are.equal(1, buffer:read())
    buffer:write(2)
    assert.are.equal(2, buffer:read())
  end)

  it('read position is maintained even across multiple writes', function()
    local buffer = CircularBuffer:new(3)
    buffer:write(1)
    buffer:write(2)
    assert.are.equal(1, buffer:read())
    buffer:write(3)
    assert.are.equal(2, buffer:read())
    assert.are.equal(3, buffer:read())
  end)

  it("items cleared out of buffer can't be read", function()
    local buffer = CircularBuffer:new(1)
    buffer:write(1)
    buffer:clear()
    assert.has_error(function()
      buffer:read()
    end, 'buffer is empty')
  end)

  it('clear frees up capacity for another write', function()
    local buffer = CircularBuffer:new(1)
    buffer:write(1)
    buffer:clear()
    buffer:write(2)
    assert.are.equal(2, buffer:read())
  end)

  it('clear does nothing on empty buffer', function()
    local buffer = CircularBuffer:new(1)
    buffer:clear()
    buffer:write(1)
    assert.are.equal(1, buffer:read())
  end)

  it('overwrite acts like write on non-full buffer', function()
    local buffer = CircularBuffer:new(2)
    buffer:write(1)
    buffer:forceWrite(2)
    assert.are.equal(1, buffer:read())
    assert.are.equal(2, buffer:read())
  end)

  it('overwrite replaces the oldest item on full buffer', function()
    local buffer = CircularBuffer:new(2)
    buffer:write(1)
    buffer:write(2)
    buffer:forceWrite(3)
    assert.are.equal(2, buffer:read())
    assert.are.equal(3, buffer:read())
  end)

  it('overwrite replaces the oldest item remaining in buffer following a read', function()
    local buffer = CircularBuffer:new(3)
    buffer:write(1)
    buffer:write(2)
    buffer:write(3)
    assert.are.equal(1, buffer:read())
    buffer:write(4)
    buffer:forceWrite(5)
    assert.are.equal(3, buffer:read())
    assert.are.equal(4, buffer:read())
    assert.are.equal(5, buffer:read())
  end)

  it('initial clear does not affect wrapping around', function()
    local buffer = CircularBuffer:new(2)
    buffer:clear()
    buffer:write(1)
    buffer:write(2)
    buffer:forceWrite(3)
    buffer:forceWrite(4)
    assert.are.equal(3, buffer:read())
    assert.are.equal(4, buffer:read())
    assert.has_error(function()
      buffer:read()
    end, 'buffer is empty')
  end)
end)
